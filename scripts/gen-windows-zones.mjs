#!/usr/bin/env node
// Regenerate internal/schedule/windowszones_gen.go from the CLDR
// windowsZones.xml table.
//
//   curl -o windowsZones.xml \
//     https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml
//   node scripts/gen-windows-zones.mjs windowsZones.xml \
//     internal/schedule/windowszones_gen.go
//
// Why the table exists: the Windows registry records the zone under a Windows
// name ("SE Asia Standard Time"), which is not an IANA name and which
// time.LoadLocation cannot resolve. CLDR's windowsZones.xml is the canonical
// mapping between the two, and this file is that mapping, compiled into the
// binary — no network access at runtime and no new dependency (AGENTS.md §4.F).
//
// Only territory="001" is kept. "001" is CLDR's world-default territory, so
// its entry is the one an install with no country-specific Windows zone
// setting resolves to. Where a zone has a country-specific entry too (for
// example "SE Asia Standard Time" territory="VN" -> Asia/Saigon), the two
// names share the same UTC offset and DST rules in practice, so the schedule
// lands on the same wall-clock slots either way.
//
// A `type` holding several space-separated zones (a territory's zone list)
// keeps only the first one; with territory="001" that does not occur, but the
// rule is applied rather than assumed.

import { readFileSync, writeFileSync } from 'node:fs'

const [xmlPath, outPath] = process.argv.slice(2)
if (!xmlPath || !outPath) {
  console.error('usage: gen-windows-zones.mjs <windowsZones.xml> <out.go>')
  process.exit(2)
}

const xml = readFileSync(xmlPath, 'utf8')

const attr = (attrs, name) => {
  const m = attrs.match(new RegExp(`${name}="([^"]*)"`))
  return m ? m[1] : ''
}

const otherVersion = (xml.match(/otherVersion="([^"]*)"/) || [, ''])[1]
const typeVersion = (xml.match(/typeVersion="([^"]*)"/) || [, ''])[1]

/** @type {{other: string, zone: string}[]} */
const rows = []
const seen = new Set()
const re = /<mapZone\b([^>]*?)\/>/g
let m
while ((m = re.exec(xml)) !== null) {
  const attrs = m[1]
  if (attr(attrs, 'territory') !== '001') continue
  const other = attr(attrs, 'other')
  const zone = attr(attrs, 'type').split(' ')[0]
  if (!other || !zone) continue
  if (seen.has(other)) {
    console.error(`duplicate territory="001" entry for ${other}; keeping the first`)
    continue
  }
  seen.add(other)
  rows.push({ other, zone })
}

rows.sort((a, b) => (a.other < b.other ? -1 : a.other > b.other ? 1 : 0))

// gofmt pads the value column of a map literal so every value starts at the
// same column: two past the longest key, the colon and one space included.
// The generator writes the same alignment rather than leaving the file to fail
// the repository's gofmt gate.
const keyWidth = Math.max(...rows.map((r) => JSON.stringify(r.other).length))
const entries = rows.map((r) => {
  const key = JSON.stringify(r.other)
  const pad = ' '.repeat(keyWidth - key.length + 1)
  return `\t${key}:${pad}${JSON.stringify(r.zone)},`
})

const go = `// Code generated by scripts/gen-windows-zones.mjs. DO NOT EDIT.
//
// Source: https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml
// CLDR windowsZones.xml otherVersion="${otherVersion}" typeVersion="${typeVersion}".
//
// Only territory="001" (the CLDR world default) is kept — see the generator for
// why, and for the rule that trims a multi-zone territory list to its first
// zone.

package schedule

// windowsZoneIANA maps a Windows time zone name (the value of the registry's
// TimeZoneKeyName) to its IANA equivalent.
//
// The map is consulted only after time.LoadLocation has already refused the
// Windows name, so an entry that the embedded tzdata cannot resolve is
// dropped rather than stored.
var windowsZoneIANA = map[string]string{
${entries.join('\n')}
}
`

writeFileSync(outPath, go)
console.log(`wrote ${rows.length} territory="001" entries to ${outPath}`)
