<script lang="ts">
  import {
    Check,
    Copy,
    Eye,
    Gavel,
    Layers,
    Pencil,
    Sparkles,
    Trash2,
    Wand2,
    X
  } from 'lucide-svelte'
  import type { Combo } from '../../api/client'
  import Card from '../../lib/ui/Card.svelte'
  import {
    comboStrategyOptions,
    effectiveComboStrategy,
    getComboModels,
    hasReasoning,
    hasVision,
    INHERIT_STRATEGY,
    resolveComboStrategy,
    isAutoGenerated,
    isAutoMember,
    smartPolicyLabel,
    smartRuleCount,
    type ComboStrategyInfo
  } from './types'

  interface Props {
    combo: Combo
    strategyInfo?: ComboStrategyInfo
    globalStrategy?: string | null
    copiedId?: string | null
    onSetStrategy: (combo: Combo, strategy: string) => void
    onOpenJudgePicker: (combo: Combo) => void
    onClearJudge: (comboName: string) => void
    onOpenRouterPicker: (combo: Combo) => void
    onOpenPolicyModal: (combo: Combo) => void
    onCopy: (name: string, id: string) => void
    onEdit: (combo: Combo) => void
    onDelete: (combo: Combo) => void
    isSelected?: boolean
    onToggleSelect?: (combo: Combo) => void
  }

  let {
    combo,
    strategyInfo = {},
    globalStrategy = null,
    copiedId = null,
    onSetStrategy,
    onOpenJudgePicker,
    onClearJudge,
    onOpenRouterPicker,
    onOpenPolicyModal,
    onCopy,
    onEdit,
    onDelete,
    isSelected = false,
    onToggleSelect,
  }: Props = $props()

  let modelsList = $derived(getComboModels(combo))
  let ruleCount = $derived(smartRuleCount(combo))

  function handleToggleSelect(e: Event) {
    e.stopPropagation()
    onToggleSelect?.(combo)
  }

  let isAutoGeneratedCombo = $derived(isAutoGenerated(combo))
  // Upstream #4576 added `inherit`, so the select has to show whichever
  // strategy the combo actually resolves to — coercing `inherit` through
  // resolveComboStrategy would pin every inheriting combo to "fallback" and
  // mislabel the dropdown. Fusion still keys off the EFFECTIVE strategy.
  let currentStrategy = $derived(
    strategyInfo.fallbackStrategy ? resolveComboStrategy(strategyInfo.fallbackStrategy) : INHERIT_STRATEGY
  )
  let judgeModel = $derived(strategyInfo.judgeModel || '')
  let isFusion = $derived(effectiveComboStrategy(strategyInfo.fallbackStrategy, globalStrategy) === 'fusion')
  let isSmart = $derived(effectiveComboStrategy(strategyInfo.fallbackStrategy, globalStrategy) === 'smart')
  let routerModel = $derived(strategyInfo.routerModel || '')
  let policyLabel = $derived(smartPolicyLabel(strategyInfo))
  let strategyOptions = $derived(comboStrategyOptions(globalStrategy))
</script>

<Card padding="sm" class="group">
  <div class="flex min-w-0 flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
    <!-- Left: Icon, Name, Model Badges & Fusion Judge -->
    <div class="flex min-w-0 flex-1 items-start gap-3 sm:items-center">
      <input
        type="checkbox"
        checked={isSelected}
        onchange={handleToggleSelect}
        class="mt-1 size-4 shrink-0 cursor-pointer accent-brand-500"
        title="Select for bulk delete"
      />
      <div class="size-8 rounded-lg bg-brand-500/10 flex items-center justify-center shrink-0">
        <Layers class="w-4 h-4 text-brand-500" />
      </div>
      <div class="min-w-0 flex-1">
        <code class="block truncate font-mono text-sm font-medium text-text-main">{combo.name}</code>
        {#if isAutoGeneratedCombo}
          <span class="mt-1 inline-flex items-center gap-1 rounded-full bg-surface-3 px-2 py-0.5 text-[10px] font-medium text-text-muted border border-border">
            <Wand2 class="w-2.5 h-2.5" />
            Auto-generated
          </span>
        {/if}
        {#if ruleCount > 0}
          <span
            class="mt-1 inline-flex items-center gap-1 rounded-full bg-brand-500/10 px-2 py-0.5 text-[10px] font-medium text-brand-500 border border-brand-500/30"
            title="{ruleCount} smart rule{ruleCount === 1 ? '' : 's'} keep this combo in step with the catalog"
          >
            <Wand2 class="w-2.5 h-2.5" />
            {ruleCount} smart rule{ruleCount === 1 ? '' : 's'}
          </span>
        {/if}
        <div class="mt-1 flex min-w-0 flex-wrap items-center gap-1">
          {#if modelsList.length === 0}
            <span class="text-xs text-text-muted italic">No models</span>
          {:else}
            {#each modelsList.slice(0, 3) as model}
              <code class="inline-flex items-center gap-1 rounded bg-black/5 dark:bg-white/5 px-1.5 py-0.5 font-mono text-xs text-text-muted">
                <span>{model}</span>
                {#if isAutoMember(combo, model)}
                  <span
                    class="text-[9px] uppercase tracking-wide text-brand-500"
                    title="Added by a smart rule, not pinned by hand"
                  >auto</span>
                {/if}
                {#if hasVision(model)}
                  <Eye class="w-3 h-3 text-blue-500 shrink-0" role="img" aria-label="Vision — supports image input" />
                {/if}
                {#if hasReasoning(model)}
                  <Sparkles class="w-3 h-3 text-amber-500 shrink-0" role="img" aria-label="Reasoning — supports reasoning / thinking" />
                {/if}
              </code>
            {/each}
            {#if modelsList.length > 3}
              <span class="text-[10px] text-text-muted">+{modelsList.length - 3} more</span>
            {/if}
          {/if}
        </div>

        <!-- Fusion: judge picker (Auto = first model) -->
        {#if isFusion}
          <div class="mt-2 flex min-w-0 flex-wrap items-center gap-1.5">
            <span class="text-[11px] font-medium text-text-muted">Judge</span>
            <button
              type="button"
              onclick={() => onOpenJudgePicker(combo)}
              class="inline-flex max-w-full items-center gap-1 rounded border border-dashed border-brand-500/40 px-1.5 py-0.5 font-mono text-[11px] text-brand-500 hover:border-brand-500 hover:bg-brand-500/5 transition-colors cursor-pointer"
              title="Pick the model that fuses panel answers"
            >
              <Gavel class="w-3 h-3" />
              <span class="truncate">{judgeModel || `Auto — ${modelsList[0] || 'first model'}`}</span>
            </button>
            {#if judgeModel}
              <button
                type="button"
                onclick={() => onClearJudge(combo.name)}
                class="p-0.5 rounded text-text-muted hover:text-red-500 hover:bg-red-500/10 transition-colors cursor-pointer"
                title="Reset judge to Auto"
              >
                <X class="w-3 h-3" />
              </button>
            {/if}
          </div>
        {/if}

        <!-- Smart Router: System One router picker and policy chip -->
        {#if isSmart}
          <div class="mt-2 flex min-w-0 flex-wrap items-center gap-1.5">
            <span class="text-[11px] font-medium text-text-muted">Router</span>
            <button
              type="button"
              onclick={() => onOpenRouterPicker(combo)}
              class="inline-flex max-w-full items-center gap-1 rounded border border-dashed border-brand-500/40 px-1.5 py-0.5 font-mono text-[11px] text-brand-500 hover:border-brand-500 hover:bg-brand-500/5 transition-colors cursor-pointer"
              title="Pick the System One model that decides model routing"
            >
              <span class="material-symbols-outlined text-[13px]">psychology</span>
              <span class="truncate">{routerModel || 'Auto — oc/jev-1.13-free'}</span>
            </button>
            <button
              type="button"
              onclick={() => onOpenPolicyModal(combo)}
              class="inline-flex items-center gap-1 rounded border border-border/70 bg-black/[0.02] dark:bg-white/[0.02] px-2 py-0.5 text-[11px] text-text-main hover:border-brand-500/50 hover:bg-brand-500/5 transition-colors cursor-pointer"
              title="Configure routing policy and prompt cache retention"
            >
              <span class="material-symbols-outlined text-[13px] text-text-muted">tune</span>
              <span class="font-medium">{policyLabel}</span>
            </button>
          </div>
        {/if}
      </div>
    </div>

    <!-- Actions: Strategy selector + Copy/Edit/Delete -->
    <div class="flex w-full flex-col gap-2 sm:w-auto sm:flex-row sm:items-center sm:gap-3 sm:shrink-0">
      <!-- Strategy dropdown -->
      <div class="w-full sm:w-[200px]">
        <select
          value={currentStrategy}
          onchange={(e) => onSetStrategy(combo, e.currentTarget.value)}
          class="w-full bg-surface-2 border border-border rounded-lg px-2.5 py-1.5 text-xs text-text-main focus:outline-none focus:border-brand-500 cursor-pointer font-body"
        >
          {#each strategyOptions as strategy (strategy.value)}
            <option value={strategy.value}>{strategy.label}</option>
          {/each}
        </select>
      </div>

      <!-- Icon buttons with labels -->
      <div class="grid grid-cols-3 gap-1 sm:flex sm:items-center">
        <button
          type="button"
          onclick={() => onCopy(combo.name, combo.id)}
          class="flex flex-col items-center justify-center rounded px-2.5 py-1 text-text-muted transition-colors hover:bg-black/5 dark:hover:bg-white/5 hover:text-brand-500 cursor-pointer"
          title="Copy combo name"
        >
          {#if copiedId === combo.id}
            <Check class="w-4 h-4 text-success" />
            <span class="text-[10px] leading-tight text-success font-medium">Copied</span>
          {:else}
            <Copy class="w-4 h-4" />
            <span class="text-[10px] leading-tight">Copy</span>
          {/if}
        </button>

        <button
          type="button"
          onclick={() => onEdit(combo)}
          class="flex flex-col items-center justify-center rounded px-2.5 py-1 text-text-muted transition-colors hover:bg-black/5 dark:hover:bg-white/5 hover:text-brand-500 cursor-pointer"
          title="Edit"
        >
          <Pencil class="w-4 h-4" />
          <span class="text-[10px] leading-tight">Edit</span>
        </button>

        <button
          type="button"
          onclick={() => onDelete(combo)}
          class="flex flex-col items-center justify-center rounded px-2.5 py-1 text-red-500 transition-colors hover:bg-red-500/10 cursor-pointer"
          title="Delete"
        >
          <Trash2 class="w-4 h-4" />
          <span class="text-[10px] leading-tight">Delete</span>
        </button>
      </div>
    </div>
  </div>
</Card>
